final licenseRepositoryProvider = Provider<LicenseRepository>((ref) {
  return LicenseRepository(ref.watch(settingsRepositoryProvider));
});

/// The shop's device slots. Re-fetch with `ref.invalidate` after adding or
/// releasing a device (no realtime/stream backing this — it's a plain
/// on-demand read of authenticated device authority).
final shopDevicesProvider = FutureProvider.autoDispose<List<ShopDevice>>((ref) {
  return ref.watch(licenseRepositoryProvider).listDevices();
});

class LicenseState {
  final bool loading;
  final CachedLicense? license;
  final LicenseStatus status;

  /// False when the cached paid/trial plan has no server receipt that
  /// verifies (see `entitlement.dart`) — Premium stays locked, selling does
  /// not. True for Free and for a verified plan.
  final bool entitled;

  const LicenseState({
    this.loading = true,
    this.license,
    this.status = LicenseStatus.none,
    this.entitled = true,
  });

  bool get canSell => status.canSell;

  /// Premium (as opposed to the always-on Free plan) — gates the optional
  /// modules in `PremiumGate`, distinct from [canSell] which only gates
  /// finalizing a sale. A lapsed paid license is still sellable but not
  /// Premium (`kind == expired`) until it renews or auto-downgrades to Free.
  bool get isPremium {
    final lic = license;
    if (lic == null || lic.plan == LicensePlan.free || !entitled) return false;
    return status.kind == LicenseStatusKind.active ||
        status.kind == LicenseStatusKind.grace;
  }
}

/// Convenience read of [LicenseState.isPremium], same shape as
/// `isEffectiveOwnerProvider` — the primary thing `PremiumGate` watches.
final isPremiumProvider = Provider<bool>(
  (ref) => ref.watch(licenseControllerProvider).isPremium,
);

/// Flips to `true` once after `LicenseController` auto-downgrades an expired
/// license to the Free plan, so Settings can show a one-time "you're on the
/// Free plan now" notice — same one-shot-notice shape as
/// `pendingAutoGeneratedExpensesProvider` in the recurring-expenses feature.
final pendingPlanDowngradeNoticeProvider = StateProvider<bool>((ref) => false);

final licenseControllerProvider =
    StateNotifierProvider<LicenseController, LicenseState>((ref) {
      return LicenseController(ref)..load();
    });

class LicenseController extends StateNotifier<LicenseState>
    with WidgetsBindingObserver {
  LicenseController(this._ref) : super(const LicenseState());

  void _startLifecycleWatch() {
    WidgetsBinding.instance.addObserver(this);
    _expiryTimer = Timer.periodic(
      const Duration(minutes: 1),
      (_) => recomputeExpiry(),
    );
    if (Env.hasBackend) {
      _authSubscription = Supabase.instance.client.auth.onAuthStateChange
          .listen((_) {
            if (mounted) recomputeExpiry();
          });
    }
  }

  /// Device clock plus monotonic elapsed time for an already-running session.
  DateTime get currentTime => DateTime.now();
  final Stopwatch _elapsedClock = Stopwatch()..start();
  DateTime? _timeAnchor;
  String? _timeAnchorShop;
  DateTime _effectiveDeviceTime(String? shopId) {
    final deviceNow = currentTime;
    if (_timeAnchor == null || shopId != _timeAnchorShop) return deviceNow;
    final elapsedNow = _timeAnchor!.add(_elapsedClock.elapsed);
    return elapsedNow.isAfter(deviceNow) ? elapsedNow : deviceNow;
  }

  Timer? _expiryTimer;
  StreamSubscription<AuthState>? _authSubscription;
  Future<void> recomputeExpiry() async {
    if (mounted) await _apply(_rawLicense);
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    if (state == AppLifecycleState.resumed) {
      recomputeExpiry();
      _silentReverify();
    }
  }

  final Ref _ref;
  Timer? _reverifyTimer;
  Future<void>? _loadFuture;

  LicenseRepository? _cachedRepo;
  LicenseRepository get _repo =>
      (_cachedRepo ??= _ref.read(licenseRepositoryProvider))!;

  /// Shared with checkout so a sale cannot race `loading: true` /
  /// `canSell == false` (status defaults to [LicenseStatus.none]).
  Future<void> load() => _loadFuture ??= _loadBody();

  Future<void> _loadBody() async {
    _startLifecycleWatch();
    final loadSeq = _applySeq;
    final lic = await _repo.current();
    if (!mounted || loadSeq != _applySeq) return;
    await _apply(lic);
    if (!mounted) return;
    // Pick up admin extensions/revocations without user action: re-verify once
    // at launch and then periodically (best-effort; offline is a no-op).
    if (Env.hasBackend) {
      _silentReverify();
      _reverifyTimer ??= Timer.periodic(
        const Duration(hours: 6),
        (_) => _silentReverify(),
      );
    }
  }

  Future<void> _silentReverify() async {
    // Signed-in shops must re-pull even when local cache is empty / Free
    // ("Not activated" after a new install). Previously we returned early
    // when license == null, so Check for renewal was the only heal path.
    if (!_repo.hasEmailSession && state.license == null) return;
    try {
      await refreshOnline();
    } catch (_) {
      /* offline / transient — keep cached */
    }
  }

  @override
  void dispose() {
    ++_applySeq;
    _cachedRepo?.cancelPendingRequests();
    _elapsedClock.stop();
    _expiryTimer?.cancel();
    _authSubscription?.cancel();
    WidgetsBinding.instance.removeObserver(this);
    _reverifyTimer?.cancel();
    super.dispose();
  }

  Future<ActivationResult> activate(String key) async {
    final result = await _repo.activate(key);
    if (result.ok && result.license != null) {
      final promoted = await _promoteFreeShopIfNeeded(result.license!.shopId);
      if (!promoted) {
        await _reopenShopDbIfNeeded(result.license!.shopId);
      }
      await _apply(result.license);
    }
    return result;
  }

  /// A Free-plan shop (`shop_id = free-<deviceId>`, purely local — see
  /// `sync_providers.dart`'s `syncEngineProvider`) has no server-side
  /// presence. Activating a key mints a real, server-assigned [toShopId]
  /// distinct from the local one — without this, [_reopenShopDbIfNeeded]
  /// would open a brand-new, empty file at [toShopId] and silently strand
  /// every local sale/product behind the old Free identity. Moves the data
  /// to travel with it instead. Returns true if a promotion ran (which
  /// already reopens the DB at the new shop), so the caller skips its own
  /// plain reopen.
  Future<bool> _promoteFreeShopIfNeeded(String toShopId) async {
    final current = state.license;
    if (current == null ||
        !current.shopId.startsWith('free-') ||
        current.shopId == toShopId ||
        !AppDatabase.usePerShopDbFiles) {
      return false;
    }
    final fromShopId = current.shopId;
    final settings = _ref.read(settingsRepositoryProvider);
    // Written before the data rewrite starts, cleared only after the file
    // rename succeeds — see `resolvePendingShopPromotion` for how a crash
    // mid-promotion is resumed on next launch.
    await settings.setPendingShopPromotion(fromShopId, toShopId);
    final db = _ref.read(databaseProvider);
    await ShopDataTransitionService(
      db,
    ).promoteShopIdentity(fromShopId: fromShopId, toShopId: toShopId);
    final session = _ref.read(databaseSessionProvider);
    await session?.reopenForShopPromotedFrom(
      fromShopId: fromShopId,
      toShopId: toShopId,
    );
    await settings.clearPendingShopPromotion();
    return true;
  }

  /// Detaches this device's key/trial. Falls back to the Free plan (same
  /// `downgradeToFree` a license lapse already uses) rather than leaving the
  /// device in a bare not-activated state — Sell/Inventory keep working, the
  /// device stays on the shop's own data, and a key can be re-entered later
  /// from the Free-plan section of this screen. Only the defensive
  /// null-license branch (unreachable via the UI — "Remove license" only
  /// ever shows for an active non-free license) still clears to nothing.
  Future<void> deactivate() async {
    final current = state.license;
    if (current == null) {
      await _repo.deactivate();
      await _apply(null);
      return;
    }
    final downgraded = await _repo.downgradeToFree(current);
    await _apply(downgraded);
  }

  /// Enters the Free plan — no key, no account, no network call. See
  /// `LicenseRepository.startFreePlan`. Currently only reachable from
  /// onboarding (a fresh device with no prior license), but guarded
  /// defensively here in case a future entry point ever calls this on a
  /// device that already has real synced data under a DIFFERENT shop: never
  /// silently mixes data under the new Free shopId. Refuses (returns false)
  /// if there are unsynced writes — same check `BranchRepository.switchBranch`
  /// uses. Legacy shared-DB mode wipes; per-shop mode reopens the Free
  /// shop file and leaves other shops' files intact.
  Future<bool> continueFree() async {
    final current = await _repo.current();
    if (current != null) {
      final db = _ref.read(databaseProvider);
      final pending = await db.select(db.outbox).get();
      if (pending.isNotEmpty) return false;
      if (!AppDatabase.usePerShopDbFiles) {
        await db.wipeSyncedData();
      }
      // Best-effort: this device is leaving `current`'s shop behind for a
      // brand-new Free-plan shop_id (see `startFreePlan`) while reusing the
      // SAME physical device_id. Release the old shop's server-side device
      // binding so it doesn't linger forever — otherwise a later
      // device_id-only /renew request (from this device, now under a
      // different shop, or a next owner after a resale) can resolve back to
      // this now-unrelated shop's license row instead of its own. Never
      // blocks the Free-plan transition if this fails or there's no backend.
      await _repo.releaseDevice(current.deviceId);
    }
    final lic = await _repo.startFreePlan();
    await _reopenShopDbIfNeeded(lic.shopId);
    await _apply(lic);
    return true;
  }

  /// Self-serve, no-account Premium trial — mirrors [activate]'s exact
  /// promote/reopen/apply shape, since both mint a real server shop_id that
  /// may need to inherit this device's local Free-plan data.
  Future<ActivationResult> startFreeTrial(String shopName) async {
    final result = await _repo.startFreeTrial(shopName);
    if (result.ok && result.license != null) {
      final promoted = await _promoteFreeShopIfNeeded(result.license!.shopId);
      if (!promoted) {
        await _reopenShopDbIfNeeded(result.license!.shopId);
      }
      await _apply(result.license);
    }
    return result;
  }

  /// See [LicenseRepository.repairSession]'s own doc comment for why this
  /// exists and what it does (re-stamps the current session from this
  /// device's existing license when the JWT already carries that shop_id)
  /// — this is the controller-level wrapper so the fix applies to
  /// app-wide state (`shopIdProvider`, cached license) the same way every
  /// other mint/activate path here does, not just the repository's own
  /// cache.
  Future<ActivationResult> repairSession() async {
    final result = await _repo.repairSession();
    if (result.ok && result.license != null) {
      await _reopenShopDbIfNeeded(result.license!.shopId);
      await _apply(result.license);
    }
    return result;
  }

  /// Re-checks the license online to pick up an extension an admin approved
  /// after a renewal payment. Signed-in shops pull by account (no key).
  /// Key-activated devices reuse `activate`. No-op offline / with no license
  /// and no account session.
  Future<ActivationResult> refreshOnline() async {
    if (!_repo.hasEmailSession) {
      return const ActivationResult.failure('account_required');
    }
    final seq = _applySeq;
    final shopId = state.license?.shopId;
    final userId = _repo.currentUserId;
    final pulled = await _repo.refreshAccountLicense(persist: false);
    if (!mounted ||
        seq != _applySeq ||
        userId != _repo.currentUserId ||
        shopId != state.license?.shopId) {
      return const ActivationResult.failure('stale_response');
    }
    if (pulled.ok &&
        pulled.license != null &&
        shopId != null &&
        pulled.license!.shopId != shopId) {
      return const ActivationResult.failure('shop_transition_required');
    }
    if (pulled.ok && pulled.license != null) {
      await _repo.saveExternal(pulled.license!);
      await applyExternal(pulled.license!);
    } else if (const [
      'device_released',
      'shop_archived',
      'membership_revoked',
    ].contains(pulled.errorCode)) {
      final current = state.license;
      if (current != null) {
        await _apply(await _repo.downgradeToFree(current));
      }
    }
    return pulled;
  }

  /// Applies a [CachedLicense] that was already persisted elsewhere (e.g. by
  /// [LicenseRepository.saveExternal] after a branch switch) — same
  /// shopId-binding + status recompute `activate()`/`load()` already do.
  /// Callers that switch shops must reopen the shop DB *before* this when
  /// [AppDatabase.usePerShopDbFiles] is on (branch/account repos do).
  Future<void> applyExternal(CachedLicense lic) async {
    if (!mounted) return;
    await _reopenShopDbIfNeeded(lic.shopId);
    if (mounted) await _apply(lic);
  }

  Future<void> _reopenShopDbIfNeeded(String shopId) async {
    if (!AppDatabase.usePerShopDbFiles || shopId.isEmpty) return;
    final session = _ref.read(databaseSessionProvider);
    await session?.reopenForShop(shopId);
  }

  /// The license as stored, before its receipt was checked. [state.license]
  /// holds the *resolved* copy (receipt expiry applied), so staleness guards
  /// compare against this instead of against what they handed to [_apply].
  CachedLicense? _rawLicense;
  int _applySeq = 0;

  Future<void> _apply(CachedLicense? lic) async {
    if (!mounted) return;
    final repo = _repo;
    final seq = ++_applySeq;
    _rawLicense = lic;
    final settings = _ref.read(settingsRepositoryProvider);

    // Check the server's receipt before trusting the cached plan/expiry, and
    // run the clock through a "never goes backwards" filter so winding the
    // phone's date back can't revive an expired plan. See entitlement.dart.
    final needsReceipt =
        lic != null && lic.plan != LicensePlan.free && Env.hasBackend;
    final receipt = needsReceipt
        ? await Entitlement.verify(lic.entitlement)
        : null;
    final highestRevision = lic == null
        ? 0
        : await settings.licenseHighestRevision(lic.shopId, lic.deviceId) ?? 0;
    final deviceId = await settings.deviceId();
    if (!mounted || seq != _applySeq) return;
    final userId = repo.currentUserId;
    final resolved = lic == null
        ? null
        : resolveEntitlement(
            cached: lic,
            entitlement: receipt,
            enforce: Env.hasBackend,
            userId: userId,
            deviceId: deviceId,
            highestRevision: highestRevision,
          );
    // Identity/revision must pass before a signed issued-at changes trusted time.
    final acceptedReceipt = resolved?.entitled == true ? receipt : null;
    final lastSeenMs = await settings.licenseLastSeenMs(shopId: lic?.shopId);
    final lastIatMs = await settings.licenseLastReceiptIatMs(
      shopId: lic?.shopId,
    );
    final time = resolveTrustedTime(
      deviceNow: _effectiveDeviceTime(lic?.shopId),
      lastSeen: lastSeenMs == null
          ? null
          : DateTime.fromMillisecondsSinceEpoch(lastSeenMs, isUtc: true),
      lastReceiptIssuedAt: lastIatMs == null
          ? null
          : DateTime.fromMillisecondsSinceEpoch(lastIatMs, isUtc: true),
      entitlement: acceptedReceipt,
    );
    if (!mounted || seq != _applySeq || userId != repo.currentUserId) return;
    if (lic != null) {
      await settings.setLicenseLastSeenMs(
        time.lastSeen.millisecondsSinceEpoch,
        shopId: lic.shopId,
      );
      if (acceptedReceipt != null) {
        await settings.setLicenseHighestRevision(
          lic.shopId,
          lic.deviceId,
          acceptedReceipt.revision,
        );
        await settings.setLicenseLastReceiptIatMs(
          acceptedReceipt.issuedAt.millisecondsSinceEpoch,
          shopId: lic.shopId,
        );
      }
    }
    if (!mounted || seq != _applySeq || userId != repo.currentUserId) return;
    _timeAnchor = time.now;
    _timeAnchorShop = lic?.shopId;
    _elapsedClock.reset();
    final effective = resolved?.license;
    final entitled = resolved?.entitled ?? true;

    final LicenseStatus status;
    if (effective != null && !entitled) {
      // Missing proof needs verification; it is not evidence of expiry.
      status = LicenseStatus(
        kind: LicenseStatusKind.verificationRequired,
        plan: effective.plan,
        expiresAt: effective.expiresAt,
      );
    } else {
      status = computeLicenseStatus(
        expiresAt: effective?.expiresAt,
        now: time.now,
        plan: effective?.plan,
        activated: effective != null,
      );
    }
    // Use the repository for the reopened shop, so staff's local floor lives
    // in the target database even on first provisioning of a new device.
    final role = repo.currentAccountRole;
    if (effective != null &&
        userId != null &&
        repo.currentSessionShopId == effective.shopId &&
        (role == 'staff' || role == 'owner')) {
      await settings.setStaffRole(effective.shopId, role!);
      if (!mounted || seq != _applySeq || userId != repo.currentUserId) return;
    }
    // Bind the active shop so all data scopes to it.
    if (effective != null) {
      _ref.read(shopIdProvider.notifier).state = effective.shopId;
    }
    state = LicenseState(
      loading: false,
      license: effective,
      status: status,
      entitled: entitled,
    );

    if (lic != null &&
        entitled &&
        lic.plan != LicensePlan.free &&
        status.kind == LicenseStatusKind.expired) {
      if (_lastLapseIdentity != '${lic.shopId}:${lic.expiresAt}') {
        _lastLapseIdentity = '${lic.shopId}:${lic.expiresAt}';
        _ref.read(pendingPlanDowngradeNoticeProvider.notifier).state = true;
      }
    }
  }

  String? _lastLapseIdentity;
}
